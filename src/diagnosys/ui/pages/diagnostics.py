"""Diagnostics page construction."""

from PySide6.QtCore import Qt, QTimer
from PySide6.QtWidgets import QGridLayout, QHBoxLayout, QLabel, QLineEdit, QPushButton, QTextBrowser
from diagnosys.diagnostics.investigation import SYMPTOMS
from diagnosys.ui.components import MetricCard, TrendChart


def build(window) -> None:
        _, layout = window._page(
            "Investigate a problem",
            "Capture what happened, review the evidence, then record whether the problem is fixed.",
        )
        symptom_card = MetricCard("1 · Choose the problem")
        symptom_grid = QGridLayout()
        symptom_grid.setHorizontalSpacing(8)
        symptom_grid.setVerticalSpacing(8)
        window.symptom_buttons: dict[str, QPushButton] = {}
        for index, symptom in enumerate(("slow_pc", "game_stutter", "internet", "app_crash", "overheating", "other")):
            button = QPushButton(SYMPTOMS[symptom]["title"])
            button.setObjectName("SymptomChoice")
            button.setCheckable(True)
            button.setMinimumHeight(44)
            button.setCursor(Qt.CursorShape.PointingHandCursor)
            button.setAccessibleDescription(SYMPTOMS[symptom]["description"])
            button.clicked.connect(lambda checked=False, item=symptom: window._select_symptom(item))
            window.symptom_buttons[symptom] = button
            symptom_grid.addWidget(button, index // 3, index % 3)
        symptom_card.content.addLayout(symptom_grid)
        window.symptom_description = QLabel(SYMPTOMS["other"]["description"])
        window.symptom_description.setObjectName("Muted")
        window.symptom_description.setWordWrap(True)
        symptom_card.content.addWidget(window.symptom_description)
        layout.addWidget(symptom_card)

        capture_card = MetricCard("2 · Capture the problem")
        capture_actions = QHBoxLayout()
        window.start_investigation_button = QPushButton("Start capturing", objectName="PrimaryButton")
        window.start_investigation_button.clicked.connect(window.start_investigation)
        window.stop_investigation_button = QPushButton("Stop & analyze")
        window.stop_investigation_button.clicked.connect(window.stop_investigation)
        window.stop_investigation_button.setEnabled(False)
        window.add_note_button = QPushButton("Add a note")
        window.add_note_button.clicked.connect(window.add_investigation_note)
        capture_actions.addWidget(window.start_investigation_button)
        capture_actions.addWidget(window.stop_investigation_button)
        capture_actions.addWidget(window.add_note_button)
        capture_actions.addStretch(1)
        capture_card.content.addLayout(capture_actions)
        network_actions = QHBoxLayout()
        window.investigation_network_hint = QLabel("For connection issues, run these focused checks while the capture is active.")
        window.investigation_network_hint.setObjectName("Muted")
        window.investigation_network_hint.setWordWrap(True)
        network_actions.addWidget(window.investigation_network_hint, 1)
        window.run_focused_check_button = QPushButton("Run connection check")
        window.run_focused_check_button.clicked.connect(window.network_check)
        window.inspect_route_button = QPushButton("Inspect route")
        window.inspect_route_button.clicked.connect(window.inspect_network_path)
        network_actions.addWidget(window.run_focused_check_button)
        network_actions.addWidget(window.inspect_route_button)
        capture_card.content.addLayout(network_actions)
        window.investigation_status = QLabel("Choose a problem, then start a capture. Diagnosys will keep collecting evidence in the background.")
        window.investigation_status.setObjectName("MetricDetail")
        window.investigation_status.setWordWrap(True)
        capture_card.content.addWidget(window.investigation_status)
        layout.addWidget(capture_card)

        result_card = MetricCard("3 · Review the findings")
        result_card.add_badge("LOCAL EVIDENCE", "PillGood")
        window.investigation_result_title = QLabel("Your findings will appear here")
        window.investigation_result_title.setObjectName("SummaryValue")
        window.investigation_result_summary = QLabel("Stop the capture after the problem occurs to compare system, process, network, and Windows event evidence.")
        window.investigation_result_summary.setObjectName("MetricDetail")
        window.investigation_result_summary.setWordWrap(True)
        window.investigation_chart = TrendChart()
        window.investigation_chart.setMinimumHeight(190)
        window.investigation_result = QTextBrowser()
        window.investigation_result.setOpenExternalLinks(False)
        window.investigation_result.setMinimumHeight(300)
        result_card.content.addWidget(window.investigation_result_title)
        result_card.content.addWidget(window.investigation_result_summary)
        result_card.content.addWidget(window.investigation_chart)
        result_card.content.addWidget(window.investigation_result, 1)
        resolution_actions = QHBoxLayout()
        window.resolve_button = QPushButton("Mark as fixed")
        window.resolve_button.clicked.connect(lambda: window.set_investigation_resolution("resolved"))
        window.unresolved_button = QPushButton("Still happening")
        window.unresolved_button.clicked.connect(lambda: window.set_investigation_resolution("still_happening"))
        window.resolution_status = QLabel("")
        window.resolution_status.setObjectName("Muted")
        window.diagnose_button = QPushButton("Analyze last hour")
        window.diagnose_button.clicked.connect(window.diagnose)
        resolution_actions.addWidget(window.diagnose_button)
        resolution_actions.addWidget(window.resolve_button)
        resolution_actions.addWidget(window.unresolved_button)
        resolution_actions.addWidget(window.resolution_status, 1)
        result_card.content.addLayout(resolution_actions)
        verification_row = QHBoxLayout()
        window.resolution_note_input = QLineEdit()
        window.resolution_note_input.setPlaceholderText("What did you change or try? (optional)")
        window.start_verification_button = QPushButton("Start 1-minute check")
        window.start_verification_button.clicked.connect(window.start_verification)
        window.compare_verification_button = QPushButton("Compare after 1 minute")
        window.compare_verification_button.clicked.connect(window.compare_verification)
        window.compare_verification_button.setEnabled(False)
        verification_row.addWidget(window.resolution_note_input, 1)
        verification_row.addWidget(window.start_verification_button)
        verification_row.addWidget(window.compare_verification_button)
        result_card.content.addLayout(verification_row)
        window.verification_status = QLabel("After trying a change, measure another minute and compare the readings with this capture.")
        window.verification_status.setObjectName("Muted")
        window.verification_status.setWordWrap(True)
        result_card.content.addWidget(window.verification_status)
        layout.addWidget(result_card)
        layout.addStretch(1)
        window.diagnosis_output = window.investigation_result
        window.capture_elapsed_timer = QTimer(window)
        window.capture_elapsed_timer.timeout.connect(window._update_capture_elapsed)
        window.verification_timer = QTimer(window)
        window.verification_timer.timeout.connect(window._update_verification_status)
        window._sync_investigation_controls()

