"""Overview page construction."""

from PySide6.QtCore import Qt
from PySide6.QtWidgets import QAbstractItemView, QGridLayout, QHBoxLayout, QHeaderView, QLabel, QPushButton, QTableWidget, QVBoxLayout
from diagnosys.diagnostics.investigation import SYMPTOMS
from diagnosys.ui.components import CircularGauge, MetricCard, ProgressMetric, SummaryCard, TrendChart


def build(window) -> None:
        _, layout = window._page("Your PC, at a glance", "Start with the problem you noticed. Diagnosys will collect evidence while it happens.")

        hero = MetricCard("What are you trying to fix?")
        hero_text = QLabel("Choose a problem to start a focused investigation. Your measurements stay on this device.")
        hero_text.setObjectName("MetricDetail")
        hero_text.setWordWrap(True)
        hero.content.addWidget(hero_text)
        choices = QGridLayout()
        choices.setHorizontalSpacing(8)
        choices.setVerticalSpacing(8)
        for index, symptom in enumerate(("slow_pc", "game_stutter", "internet", "app_crash", "overheating", "other")):
            button = QPushButton(SYMPTOMS[symptom]["title"])
            button.setObjectName("SymptomChoice")
            button.setMinimumHeight(42)
            button.setCursor(Qt.CursorShape.PointingHandCursor)
            button.setAccessibleDescription(SYMPTOMS[symptom]["description"])
            button.clicked.connect(lambda checked=False, item=symptom: window._open_investigation(item))
            choices.addWidget(button, index // 3, index % 3)
        hero.content.addLayout(choices)
        window.active_capture_label = QLabel("No active investigation")
        window.active_capture_label.setObjectName("Muted")
        hero.content.addWidget(window.active_capture_label)
        layout.addWidget(hero)

        summaries = QHBoxLayout()
        summaries.setSpacing(12)
        window.host_summary = SummaryCard("Device", "—", "Hostname")
        window.uptime_summary = SummaryCard("Uptime", "—", "Since last boot")
        window.os_summary = SummaryCard("Operating system", "—", "Platform details")
        for card in (window.host_summary, window.uptime_summary, window.os_summary):
            summaries.addWidget(card, 1)
        layout.addLayout(summaries)

        status_grid = QGridLayout()
        status_grid.setHorizontalSpacing(12)
        status_grid.setVerticalSpacing(10)
        window.thermal_overview = SummaryCard("Thermal", "Checking", "Sensor availability")
        window.disk_health_overview = SummaryCard("Disk health", "Unknown", "SMART data not checked yet")
        window.gaming_overview = SummaryCard("Gaming session", "Not configured", "Add process names in Settings")
        window.recent_events_overview = SummaryCard("Recent findings", "Checking", "Recent diagnostic evidence")
        status_grid.addWidget(window.thermal_overview, 0, 0)
        status_grid.addWidget(window.disk_health_overview, 0, 1)
        status_grid.addWidget(window.gaming_overview, 1, 0)
        status_grid.addWidget(window.recent_events_overview, 1, 1)
        layout.addLayout(status_grid)

        metrics = QGridLayout()
        metrics.setHorizontalSpacing(12)
        metrics.setVerticalSpacing(12)

        window.cpu_card = MetricCard("Processor")
        cpu_row = QHBoxLayout()
        cpu_row.setSpacing(14)
        window.cpu_gauge = CircularGauge("CPU LOAD")
        cpu_row.addWidget(window.cpu_gauge, 0, Qt.AlignmentFlag.AlignVCenter)
        cpu_info = QVBoxLayout()
        cpu_info.setSpacing(12)
        cpu_info.addStretch(1)
        pair, window.cpu_frequency = window._pair("CURRENT FREQUENCY")
        cpu_info.addWidget(pair)
        pair, window.cpu_temperature = window._pair("TEMPERATURE")
        cpu_info.addWidget(pair)
        window.cpu_cores = window._muted_label("Logical processors —")
        cpu_info.addWidget(window.cpu_cores)
        cpu_info.addStretch(1)
        cpu_row.addLayout(cpu_info, 1)
        window.cpu_card.content.addLayout(cpu_row, 1)
        metrics.addWidget(window.cpu_card, 0, 0)

        window.memory_card = MetricCard("Memory")
        window.memory_value = QLabel("— / —")
        window.memory_value.setObjectName("MetricValue")
        window.memory_card.content.addWidget(window.memory_value)
        window.memory_progress = ProgressMetric("In use")
        window.memory_card.content.addWidget(window.memory_progress)
        window.memory_available = window._muted_label("Available memory —")
        window.memory_card.content.addStretch(1)
        window.memory_card.content.addWidget(window.memory_available)
        metrics.addWidget(window.memory_card, 0, 1)

        window.disk_card = MetricCard("Storage & disk activity")
        window.disk_card.add_badge("SYSTEM VOLUME", "PillGood")
        window.disk_value = QLabel("— / —")
        window.disk_value.setObjectName("MetricValue")
        window.disk_card.content.addWidget(window.disk_value)
        window.disk_progress = ProgressMetric("Space used")
        window.disk_card.content.addWidget(window.disk_progress)
        io_row = QHBoxLayout()
        io_row.setSpacing(16)
        pair, window.disk_read = window._pair("READ")
        io_row.addWidget(pair)
        pair, window.disk_write = window._pair("WRITE")
        io_row.addWidget(pair)
        window.disk_card.content.addLayout(io_row)
        metrics.addWidget(window.disk_card, 1, 0)

        window.network_card = MetricCard("Network")
        window.network_card.add_badge("INTERFACE ACTIVITY", "PillGood")
        rates = QHBoxLayout()
        rates.setSpacing(12)
        down = QVBoxLayout()
        down.setSpacing(3)
        down.addWidget(QLabel("DOWNLOAD", objectName="TinyLabel"))
        window.download_value = QLabel("—")
        window.download_value.setObjectName("MetricValue")
        down.addWidget(window.download_value)
        rates.addLayout(down, 1)
        up = QVBoxLayout()
        up.setSpacing(3)
        up.addWidget(QLabel("UPLOAD", objectName="TinyLabel"))
        window.upload_value = QLabel("—")
        window.upload_value.setObjectName("MetricValue")
        up.addWidget(window.upload_value)
        rates.addLayout(up, 1)
        window.network_card.content.addLayout(rates)
        network_bottom = QHBoxLayout()
        window.ping_summary = window._muted_label("Latency — · Packet loss —")
        network_bottom.addWidget(window.ping_summary, 1)
        check_network = QPushButton("Test connection")
        check_network.setCursor(Qt.CursorShape.PointingHandCursor)
        check_network.clicked.connect(window.network_check)
        network_bottom.addWidget(check_network)
        window.network_card.content.addLayout(network_bottom)
        metrics.addWidget(window.network_card, 1, 1)

        window.gpu_card = MetricCard("Graphics processor")
        window.gpu_badge = window.gpu_card.add_badge("UNAVAILABLE", "PillNeutral")
        window.gpu_name = window._muted_label("GPU telemetry is not available on this device.")
        window.gpu_card.content.addWidget(window.gpu_name)
        window.gpu_progress = ProgressMetric("Utilization")
        window.gpu_card.content.addWidget(window.gpu_progress)
        gpu_detail = QHBoxLayout()
        pair, window.gpu_memory = window._pair("VIDEO MEMORY")
        gpu_detail.addWidget(pair)
        pair, window.gpu_temperature = window._pair("TEMPERATURE")
        gpu_detail.addWidget(pair)
        window.gpu_card.content.addLayout(gpu_detail)
        metrics.addWidget(window.gpu_card, 2, 0)

        window.insight_card = MetricCard("Diagnostic insights")
        window.insight_card.add_badge("LOCAL · RULE BASED", "PillGood")
        window.insight_title = QLabel("Gathering recent evidence")
        window.insight_title.setObjectName("SummaryValue")
        window.insight_body = window._muted_label("Recommendations are based on measurements collected by Diagnosys.")
        window.insight_evidence = window._muted_label("")
        insight_actions = QHBoxLayout()
        view_diagnosis = QPushButton("View evidence", objectName="PrimaryButton")
        view_diagnosis.setCursor(Qt.CursorShape.PointingHandCursor)
        view_diagnosis.clicked.connect(lambda: window._navigate(2))
        insight_actions.addStretch(1)
        insight_actions.addWidget(view_diagnosis)
        window.insight_card.content.addWidget(window.insight_title)
        window.insight_card.content.addWidget(window.insight_body)
        window.insight_card.content.addWidget(window.insight_evidence)
        window.insight_card.content.addStretch(1)
        window.insight_card.content.addLayout(insight_actions)
        metrics.addWidget(window.insight_card, 2, 1)
        metrics.setColumnStretch(0, 1)
        metrics.setColumnStretch(1, 1)
        layout.addLayout(metrics)

        chart_card = MetricCard("Resource history")
        chart_card.add_badge("LAST 60 SAMPLES", "PillGood")
        window.chart = TrendChart()
        chart_card.content.addWidget(window.chart)
        layout.addWidget(chart_card)

        process_card = MetricCard("Top processes")
        process_card.add_badge("LIVE SNAPSHOT", "PillGood")
        window.process_table = QTableWidget(6, 4)
        window.process_table.setHorizontalHeaderLabels(("Highest CPU", "CPU", "Highest memory", "Memory"))
        window.process_table.verticalHeader().setVisible(False)
        window.process_table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        window.process_table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        window.process_table.setAlternatingRowColors(True)
        window.process_table.setShowGrid(False)
        window.process_table.setMinimumHeight(230)
        window.process_table.setMaximumHeight(260)
        header = window.process_table.horizontalHeader()
        header.setSectionResizeMode(0, QHeaderView.ResizeMode.Stretch)
        header.setSectionResizeMode(1, QHeaderView.ResizeMode.ResizeToContents)
        header.setSectionResizeMode(2, QHeaderView.ResizeMode.Stretch)
        header.setSectionResizeMode(3, QHeaderView.ResizeMode.ResizeToContents)
        process_card.content.addWidget(window.process_table)
        layout.addWidget(process_card)
        layout.addStretch(1)

